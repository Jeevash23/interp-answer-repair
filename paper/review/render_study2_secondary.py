"""Render the Study 2 prespecified secondary geometry table (version 3.2) from the saved, verified secondary analysis.

Reads studies/bridge-007/results/secondary-analysis/summary.json (frozen secondary-analysis implementation;
replayed exactly by `make replay-extensions`) and writes sections/study2-secondary-table.tex: movement from
the corrupted signature and the three alternative distance margins after wording transfer, pooled over the
3,200 final configurations with pointwise 95% crossed-bootstrap intervals. No new computation.
"""
from pathlib import Path
import hashlib
import json

REV = Path(__file__).resolve().parents[1]
ROOT = REV.parent
SOURCE = ROOT / 'studies/bridge-007/results/secondary-analysis/summary.json'
REFS = ('zero', 'fit_mean')
MOVEMENT = [('Progress along $\\Cc \\to \\Rr$, wording', 'wording', 'progress_toward_recipient'),
            ('Progress along $\\Cc \\to \\Rr$, self', 'self', 'progress_toward_recipient'),
            ('Recipient distance closed, wording', 'wording', 'recipient_distance_closed'),
            ('Cosine with $\\Cc \\to \\Rr$, wording', 'wording', 'cosine_with_ideal_repair'),
            ('Perpendicular share of squared movement, wording', 'wording', 'perpendicular_fraction'),
            ('Perpendicular share, perfect repair $\\Cc \\to \\Rr$', 'wording', 'ideal_repair_perpendicular_fraction')]
DISTANCES = [('Margin, unscaled paired L2', 'unscaled_paired_l2'), ('Margin, standardised cosine', 'standardized_cosine'),
             ('Margin, centroid-normalised L2', 'centroid_normalized_l2')]


def num(x, places=3):
    if abs(x) < .5 * 10 ** (-places):
        x = 0
    return f'{x:.{places}f}'


def ci(v):
    assert v['valid'] and v['interval_scope'] == 'pointwise 95%' and v['multiplicity'] == 1
    return '$' + num(v['mean']) + r'\ci{' + num(v['ci95'][0]) + '}{' + num(v['ci95'][1]) + '}$'


def main():
    s = json.loads(SOURCE.read_text())
    assert s['scope'] == 'Prespecified secondary analyses; no primary decision changes' and s['n'] == 3200
    cells = [v for _, key in DISTANCES for ref in REFS for v in s['alternative_distances']['wording'][key][ref]['cells'].values()]
    assert len(cells) == 24 and all(v['ci95'][1] < 0 for v in cells)  # every cell interval favours the recipient
    lines = [r'\begin{table}[htbp]', r'\centering\small',
             r'\caption{Study 2 prespecified secondary geometry on the 3,200 final configurations: movement from the corrupted '
             r'signature (as in \cref{tab:movement} for Study 1) and alternative distance margins after wording transfer. '
             r'Pooled means with pointwise 95\% crossed-bootstrap intervals. For each alternative distance, all eight cell '
             r'intervals (four wording--order cells, two references) also lie below zero. Negative margins favour the clean recipient.}',
             r'\label{tab:confirmation-secondary-geometry}', r'\begin{tabular}{@{}lcc@{}}', r'\toprule',
             r'Quantity & Zero replacement & Mean replacement \\', r'\midrule']
    for label, condition, key in MOVEMENT:
        lines.append(label + ' & ' + ' & '.join(ci(s['movement'][condition][key][ref]['pooled']) for ref in REFS) + r' \\')
    lines.append(r'\midrule')
    for label, key in DISTANCES:
        lines.append(label + ' & ' + ' & '.join(ci(s['alternative_distances']['wording'][key][ref]['pooled']) for ref in REFS) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    header = (f'% Generated by review/render_study2_secondary.py from studies/bridge-007/results/secondary-analysis/summary.json\n'
              f'% (SHA-256 {digest}); prespecified secondary results, version 3.2.\n')
    (REV / 'sections/study2-secondary-table.tex').write_text(header + '\n'.join(lines))
    print('wrote sections/study2-secondary-table.tex')


if __name__ == '__main__':
    main()
