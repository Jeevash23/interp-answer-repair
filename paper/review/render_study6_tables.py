"""Render the Study 6 (positive control) tables from its saved, verified summaries (version 3.3).

    python3 paper/review/render_study6_tables.py           # write sections/positive-control-*.tex
    python3 paper/review/render_study6_tables.py --check   # fail if the written tables differ
"""
from pathlib import Path
import hashlib
import json
import sys

REV = Path(__file__).resolve().parents[1]
ROOT = REV.parent
STUDY = ROOT / 'studies/bridge-011'
REFS = ('zero', 'fit_mean')
NAMES = dict(clean='Clean recipient', corrupt='Corrupted, no edit', wording='Wording transfer', self='Self transfer',
             self_kappa='Self transfer at dose $\\kappa$', n1='$N_1$: clean, name movers held',
             n2='$N_2$: self transfer, name movers held', order='$O$: order donor', replay='$X$: full layer-13 replay')
SHORT = dict(clean='Clean recipient', corrupt='Corrupted, no edit', wording='Wording transfer', self='Self transfer',
             self_kappa='Self transfer, dose $\\kappa$', n1='$N_1$ (clean, heads held)', n2='$N_2$ (self, heads held)',
             order='$O$ (order donor)', replay='$X$ (full replay)')
CONTROLS = (('n1', '$N_1$ vs clean recipient'), ('n2', '$N_2$ vs self transfer at dose $\\kappa$'),
            ('order', '$O$ vs clean recipient'))
BANDS = dict(detected='detected', intermediate='intermediate', below_resolution='below 0.5')


def read(p):
    return json.loads(Path(p).read_text())


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def num(x, digits=3):
    return f'{x:.{digits}f}'


def ci(v, key='ci95', digits=3):
    return '$' + num(v['mean'], digits) + r'\ci{' + num(v[key][0], digits) + '}{' + num(v[key][1], digits) + '}$'


def head(h):
    return f'L{h[0]}H{h[1]}'


def main_table(s, dev, digest):
    rows = []
    for control, label in CONTROLS:
        cells = [ci(s['primary'][control][ref], 'adjusted_ci') + ' & ' + BANDS[s['primary'][control][ref]['band']]
                 for ref in REFS]
        rows.append(label + ' & ' + ' & '.join(cells) + r' \\')
    f = [s['replication']['retained'][ref]['mean_full_signature_distance'] for ref in REFS]
    dose = [s['amplitude']['dose_only_distance'][ref] for ref in REFS]
    anchor = s['anchor']
    held = ', '.join(head(h) for h in dev['held'])
    return '\n'.join([
        f'% Generated by review/render_study6_tables.py from studies/bridge-011 results (analysis summary SHA-256 {digest}).',
        r'\begin{table}[htbp]', r'\centering\small',
        r'\caption{Study 6, held-out bank (3,200 configurations from 20 context blocks and 20 name triples): distance of each '
        r'positive control from the condition it is known to differ from, in clean wording separations, over the 176 END heads '
        f'except the three held name movers ({held}). Means with Bonferroni-adjusted crossed-bootstrap intervals (six-quantity '
        r"family). A control detects its change when the adjusted lower limit exceeds 1; ``below 0.5'' means that the adjusted "
        r"upper limit is below Study~2's full-discrepancy bound. The lower rows give, on the same rows and coordinates, the "
        r'wording/self discrepancy, the distance between self transfer at full and reduced dose, and the full replay anchor '
        r'(pointwise 95\% intervals).}',
        r'\label{tab:positive-control}', r'\footnotesize\setlength{\tabcolsep}{3pt}',
        r'\begin{tabular}{@{}lcccc@{}}', r'\toprule',
        r' & \multicolumn{2}{c}{Zero replacement} & \multicolumn{2}{c}{Mean replacement} \\',
        r'\cmidrule(lr){2-3}\cmidrule(l){4-5}',
        r'Comparison & Distance & Reading & Distance & Reading \\', r'\midrule', *rows, r'\addlinespace',
        r'Wording vs self transfer & ' + ci(f[0]) + ' & & ' + ci(f[1]) + r' & \\',
        r'Self transfer: dose 1 vs $\kappa$ & ' + ci(dose[0]) + ' & & ' + ci(dose[1]) + r' & \\',
        r'$X$: from clean recipient / from donor & ' + num(anchor['q_recipient_mean'][0]) + ' / ' + num(anchor['q_donor_max']) +
        ' & & ' + num(anchor['q_recipient_mean'][1]) + ' / ' + num(anchor['q_donor_max']) + r' & \\',
        r'\bottomrule', r'\end{tabular}', r'\end{table}', ''])


def geometry_table(s, digest):
    rows = []
    for name in ('corrupt', 'wording', 'self', 'self_kappa', 'n1', 'n2', 'order', 'replay'):
        g = s['geometry'][name]
        rows.append(SHORT[name] + ' & ' + ' & '.join(ci(g[ref][key]) for ref in REFS for key in ('q_recipient', 'margin')) + r' \\')
    return '\n'.join([
        r'\begin{table}[htbp]', r'\centering\small',
        r'\caption{Study 6, held-out bank: distance of every condition from the clean recipient ($q_R$) and distance margin '
        r"$M = q_R - q_D$, in clean wording separations over the retained 173 heads; ``heads held'' means the three name movers held at their mean. Negative margins favour the recipient. "
        r'Pointwise 95\% crossed-bootstrap intervals.}',
        r'\label{tab:positive-control-geometry}', r'\footnotesize\setlength{\tabcolsep}{3pt}',
        r'\begin{tabular}{@{}lcccc@{}}', r'\toprule',
        r' & \multicolumn{2}{c}{Zero replacement} & \multicolumn{2}{c}{Mean replacement} \\',
        r'\cmidrule(lr){2-3}\cmidrule(l){4-5}', r'Condition & $q_R$ & $M$ & $q_R$ & $M$ \\', r'\midrule',
        *rows, r'\bottomrule', r'\end{tabular}', r'\end{table}', ''])


def behaviour_table(s, digest):
    rows = []
    for name in ('clean', 'corrupt', 'wording', 'self', 'self_kappa', 'n1', 'n2', 'order', 'replay'):
        b = s['behaviour'][name]
        pct = lambda v: dict(mean=100 * v['mean'], ci95=[100 * x for x in v['ci95']])
        rows.append(SHORT[name] + ' & ' + ci(b['gap']) + ' & ' + ci(pct(b['top1']), digits=1) + ' & ' +
                    ci(pct(b['pairwise']), digits=1) + r' \\')
    a = s['attribution']
    comp = [a['compensation_n1_vs_clean'], a['compensation_n2_vs_self']]
    share = [a[k]['held_share_of_gap'] for k in ('clean', 'self')]
    return '\n'.join([
        r'\begin{table}[htbp]', r'\centering\small',
        r'\caption{Study 6, held-out bank: behaviour of every condition (logit gap, top-1 and pairwise accuracy in per cent), '
        r"and direct attribution of the three held name movers. ``Share'' is their summed direct attribution as a fraction of "
        r"the logit gap; ``recovered'' is the gain in the other heads' summed direct attribution as a fraction of the held "
        r"heads' loss when they are held at the mean. Pointwise 95\% crossed-bootstrap intervals.}",
        r'\label{tab:positive-control-behaviour}', r'\footnotesize\setlength{\tabcolsep}{4pt}',
        r'\begin{tabular}{@{}lccc@{}}', r'\toprule', r'Condition & Logit gap & Top-1 (\%) & Pairwise (\%) \\', r'\midrule',
        *rows, r'\addlinespace',
        r'Held heads: share, clean / self transfer & \multicolumn{3}{c}{' + ci(share[0]) + ' / ' + ci(share[1]) + r'} \\',
        r'Held heads: recovered, $N_1$ / $N_2$ & \multicolumn{3}{c}{' + ci(comp[0]['fraction_recovered']) + ' / ' +
        ci(comp[1]['fraction_recovered']) + r'} \\',
        r'\bottomrule', r'\end{tabular}', r'\end{table}', ''])


def secondary_table(s, digest):
    rows = []
    for control, label in CONTROLS[:2]:
        key = f'{control}_over_F'
        rows.append(label + ': ratio to wording/self & ' + ' & '.join(ci(s['ratios_to_wording_self'][key][ref]) for ref in REFS) + r' \\')
    for key, label in (('shape_n1_vs_clean', '$N_1$ vs clean recipient: after best rescaling'),
                       ('shape_n2_vs_self_kappa', '$N_2$ vs dose $\\kappa$: after best rescaling'),
                       ('shape_self_kappa_vs_self', 'Dose $\\kappa$ vs self transfer: after best rescaling')):
        rows.append(label + ' & ' + ' & '.join(ci(s['amplitude'][key][ref]['distance']) for ref in REFS) + r' \\')
    for control, label in CONTROLS:
        rows.append(label + ': all 176 heads & ' + ' & '.join(ci(s['primary_all176'][control][ref]) for ref in REFS) + r' \\')
    cells = []
    for control, label in CONTROLS:
        for cell in ('w0_o0', 'w0_o1', 'w1_o0', 'w1_o1'):
            w, o = int(cell[1]), int(cell[4])
            cells.append(label + f', F{10 + w} / order {o} & ' +
                         ' & '.join(ci(s['primary_cells'][control][ref][cell]) for ref in REFS) + r' \\')
    return '\n'.join([
        r'\begin{table}[htbp]', r'\centering\small',
        r'\caption{Study 6, held-out bank: prespecified secondary quantities for the positive controls, in clean wording '
        r"separations unless stated. Ratios divide each control's mean distance by the mean wording/self discrepancy on the "
        r"same rows; ``after best rescaling'' removes the best multiple of the comparator, configuration by configuration; "
        r'the last rows give each primary distance by recipient wording and mention order. Pointwise 95\% crossed-bootstrap '
        r'intervals.}',
        r'\label{tab:positive-control-secondary}', r'\footnotesize\setlength{\tabcolsep}{4pt}',
        r'\begin{tabular}{@{}lcc@{}}', r'\toprule', r'Quantity & Zero replacement & Mean replacement \\', r'\midrule',
        *rows, r'\addlinespace', *cells, r'\bottomrule', r'\end{tabular}', r'\end{table}', ''])


def development_table(dev, sd):
    c = dev['candidates'][:6]
    trial = dev['trials'][-1]
    rows = [head(x['head']) + ' & ' + num(x['mean_dla']) + ' & ' + ' / '.join(num(v) for v in x['attention_io_s1_s2']) + r' \\'
            for x in c]
    prim = []
    for control, label in CONTROLS:
        prim.append(label + ' & ' + ' & '.join(ci(sd['primary'][control][ref], 'adjusted_ci') for ref in REFS) + r' \\')
    return '\n'.join([
        r'\begin{table}[htbp]', r'\centering\small',
        r'\caption{Study 6, development bank (288 configurations from six context blocks and six name triples). Top: the six '
        r'highest-ranked name-mover candidates by mean direct logit attribution (logits), with mean END attention to the '
        r'indirect object, first subject mention and S2. The first three were held. Bottom: the primary distances on the '
        r'development bank, which fixed no threshold (Bonferroni-adjusted intervals, six-quantity family).}',
        r'\label{tab:positive-control-development}', r'\footnotesize\setlength{\tabcolsep}{4pt}',
        r'\begin{tabular}{@{}lcc@{}}', r'\toprule', r'Head & Direct attribution & Attention to IO / S1 / S2 \\', r'\midrule',
        *rows, r'\midrule', r'Comparison & Zero replacement & Mean replacement \\', r'\midrule', *prim,
        r'\bottomrule', r'\end{tabular}', r'\end{table}', ''])


def render():
    summary = STUDY / 'results/analysis/summary.json'
    s, dev = read(summary), read(STUDY / 'results/development.json')
    sd = read(STUDY / 'results/analysis-development/summary.json')
    digest = sha(summary)
    main = main_table(s, dev, digest)
    rest = '\n'.join([f'% Generated by review/render_study6_tables.py from studies/bridge-011 results (analysis summary SHA-256 {digest}).',
                      development_table(dev, sd), geometry_table(s, digest), behaviour_table(s, digest), secondary_table(s, digest)])
    return {REV / 'sections/positive-control-main-table.tex': main, REV / 'sections/positive-control-tables.tex': rest}


def main():
    outputs = render()
    if '--check' in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        assert not stale, stale
        print('Study 6 tables match the saved summaries')
        return
    for path, text in outputs.items():
        path.write_text(text)
    print('wrote', ', '.join(str(p.relative_to(ROOT)) for p in outputs))


if __name__ == '__main__':
    main()
