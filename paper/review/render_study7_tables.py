"""Render the Study 7 (GPT-2 Large) tables from its saved stage records (version 3.4).

    python3 paper/review/render_study7_tables.py           # write sections/large-attempt-tables.tex
    python3 paper/review/render_study7_tables.py --check   # fail if the written tables differ
"""
from pathlib import Path
import hashlib
import json
import sys

REV = Path(__file__).resolve().parents[1]
ROOT = REV.parent
STUDY = ROOT / 'studies/bridge-012/results'
TARGET = REV / 'sections/large-attempt-tables.tex'


def read(name):
    return json.loads((STUDY / name).read_text())


def sha(name):
    return hashlib.sha256((STUDY / name).read_bytes()).hexdigest()


def pct(x):
    return f'{100 * x:.1f}'


def render():
    screen, selection = read('screen.json'), read('selection.json')
    gate = lambda c: 'passed' if all(v['pairwise'] >= 0.95 and v['top1'] >= 0.85 for v in c.values()) else 'failed'
    rows = []
    for family, cells in sorted(screen['cells'].items()):
        line = [f'F{family}']
        for order in ('0', '1'):
            v = cells[order]
            line += [pct(v['pairwise']), pct(v['top1']), f"{v['logit']:.2f}"]
        rows.append(' & '.join(line + [gate(cells)]) + r' \\')
    pair = selection['scores']['10,13']
    labels = [('10', '0', 'w0_o0'), ('10', '1', 'w0_o1'), ('13', '0', 'w1_o0'), ('13', '1', 'w1_o1')]
    sel_rows = []
    for title, key in (('Fit top-1', 'fit_behavior'), ('Selection top-1', 'selection_behavior')):
        sel_rows.append(title + ' & ' + ' & '.join(pct(pair[key][f][o]['top1']) for f, o, _ in labels) + r' \\')
    for title, key in (('Fit classification', 'fit_separation'), ('Selection classification', 'selection_separation')):
        sel_rows.append(title + ' & ' + ' & '.join(' / '.join(pct(x) for x in pair[key][c]) for _, _, c in labels) + r' \\')
    return '\n'.join([
        '% Generated by review/render_study7_tables.py from studies/bridge-012/results '
        f"(screen.json SHA-256 {sha('screen.json')}; selection.json SHA-256 {sha('selection.json')}).",
        r'\begin{table}[H]', r'\centering\footnotesize', r'\setlength{\tabcolsep}{3pt}',
        r'\caption{Study 7: GPT-2 Large behavioural screen on 48 fresh configurations per family (three context blocks, '
        r'four name triples). Pairwise and top-1 accuracy in per cent and the mean logit gap, by mention order. Each '
        r'family must reach 95\% pairwise and 85\% top-1 accuracy in both orders.}',
        r'\label{tab:large-screen}', r'\begin{tabular}{@{}lccccccc@{}}', r'\toprule',
        r' & \multicolumn{3}{c}{Order 0} & \multicolumn{3}{c}{Order 1} & \\', r'\cmidrule(lr){2-4}\cmidrule(lr){5-7}',
        r'Family & Pairwise & Top-1 & Gap & Pairwise & Top-1 & Gap & Screen \\', r'\midrule', *rows,
        r'\bottomrule', r'\end{tabular}', r'\end{table}', '',
        r'\begin{table}[H]', r'\centering\footnotesize', r'\setlength{\tabcolsep}{4pt}',
        r'\caption{Study 7: selection of the only eligible pair, F10/F13, in GPT-2 Large (256 configurations per family in '
        r'each bank). Top-1 accuracy in per cent (pairwise accuracy was 100\% throughout) and the clean classification '
        r'rate under zero / mean replacement. Selection requires the behavioural gates in both banks, at least 80\% '
        r'classification in every fitting cell and at least 90\% in every selection cell. The selection-bank top-1 rates '
        r'of F13 and the F10, order~0 selection classification fall below their gates.}',
        r'\label{tab:large-selection}', r'\begin{tabular}{@{}lcccc@{}}', r'\toprule',
        r' & F10 / 0 & F10 / 1 & F13 / 0 & F13 / 1 \\', r'\midrule', *sel_rows, r'\bottomrule', r'\end{tabular}',
        r'\end{table}', ''])


def main():
    text = render()
    if '--check' in sys.argv:
        assert TARGET.exists() and TARGET.read_text() == text, 'Study 7 tables differ from the saved records'
        print('Study 7 tables match the saved records')
        return
    TARGET.write_text(text)
    print('wrote', TARGET.relative_to(ROOT))


if __name__ == '__main__':
    main()
